"""Register the fortification plans of 1658 and 1703 (Historický atlas měst ČR 21 – Plzeň, maps 5 and 6)
to S-JTSK and convert the works traced on them to map coordinates.

Both plans are hand-drawn with west at the top. Registration: the medieval wall ring traced on each plan
(`ring` in fort_plans.json, plan coordinates = half-scale pixels of a 300-dpi page crop, see `origin`) is
aligned to the wall ring of the 1536–1618 model by ECC (translation, then affine) on blurred masks,
starting from a similarity guess (centroids, area ratio, west up). The traced works (`works`) are then
transformed with that affine. Expect errors of 10–30 m: the plans are not surveyed. The surveyed 1781
plan (fort_1781.json) stays the geometry source for every work it shows; the 1658 / 1703 traces give
phases and the works missing in 1781.

usage: python fort_plans.py        (paths relative to the repository)
reads  scripts/fort_plans.json, apps/historic-mapper/projects/plzen.json, data/reference/hiu-atlas/pages/p04{3,4}_300.png
writes scripts/fort_plans_map.json (versioned: works in EPSG:5514 + transforms) and data/historic/growth/fort/_reg_*.jpg
"""
import json, os
import cv2
import numpy as np
from shapely.geometry import Polygon

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
CFG = json.load(open(os.path.join(HERE, 'fort_plans.json'), encoding='utf-8'))
P = json.load(open(os.path.join(ROOT, 'apps', 'historic-mapper', 'projects', 'plzen.json'), encoding='utf-8'))
ENT = {e['id']: e for e in P['entities']}
WALL = np.array(ENT['g1618-wall']['geom']['coords'], float)
F81 = json.load(open(os.path.join(HERE, 'fort_1781.json'), encoding='utf-8'))
OUTD = os.path.join(ROOT, 'data', 'historic', 'growth', 'fort'); os.makedirs(OUTD, exist_ok=True)
S = 1200  # canvas of half-scale plan coordinates


def fill(poly, A=None):
    m = np.zeros((S, S), np.uint8)
    p = np.asarray(poly, float)
    if A is not None: p = np.c_[p, np.ones(len(p))] @ A.T
    cv2.fillPoly(m, [np.round(p).astype(np.int32)], 255)
    return m


out = {'crs': 'EPSG:5514', 'note': 'generated by fort_plans.py from fort_plans.json; plan affines map half-scale plan px → EPSG:5514', 'plans': {}}
for pid, pl in CFG['plans'].items():
    ring = np.array(pl['ring'], float)
    rp, wp = Polygon(ring), Polygon(WALL)
    s = np.sqrt(wp.area / rp.area)
    cu, cv = rp.centroid.x, rp.centroid.y
    # west at the top, north to the right: x = cx + s (v - cv), y = cy + s (u - cu)
    A0 = np.array([[0, s, wp.centroid.x - s * cv], [s, 0, wp.centroid.y - s * cu]])
    inv = cv2.invertAffineTransform(A0)
    ref = fill(WALL, inv)                 # model wall ring in the plan frame (initial guess)
    mp = fill(ring)
    warp = np.eye(2, 3, dtype=np.float32); cc = 0
    for motion, sig in ((cv2.MOTION_TRANSLATION, 12), (cv2.MOTION_AFFINE, 8), (cv2.MOTION_AFFINE, 4)):
        t = lambda m: cv2.GaussianBlur(m.astype(np.float32) / 255, (0, 0), sig)
        cc, warp = cv2.findTransformECC(t(ref), t(mp), warp, motion, (cv2.TERM_CRITERIA_EPS | cv2.TERM_CRITERIA_COUNT, 500, 1e-7), None, 5)
    Wi = cv2.invertAffineTransform(warp)
    A = (np.r_[A0, [[0, 0, 1]]] @ np.r_[Wi, [[0, 0, 1]]])[:2]
    tr = lambda pts: (np.c_[np.asarray(pts, float), np.ones(len(pts))] @ A.T)
    iou = Polygon(tr(ring)).intersection(wp).area / Polygon(tr(ring)).union(wp).area
    chk = {}
    for name, (u, v) in pl.get('check', {}).items():
        x, y = tr([(u, v)])[0]
        ref_xy = ENT[name]['geom']['coords'][0] if name in ENT else None
        chk[name] = round(float(np.hypot(x - ref_xy[0], y - ref_xy[1])), 1) if ref_xy else None
    works = []
    for w in pl['works']:
        xy = tr(w['poly'])
        works.append({k: v for k, v in w.items() if k != 'poly'} | {'poly': [[round(a, 1), round(b, 1)] for a, b in xy]})
    out['plans'][pid] = {'title': pl['title'], 'affine': np.round(A, 6).tolist(), 'ecc': round(float(cc), 3), 'iou_ring': round(iou, 3),
                         'check_m': chk, 'works': works}
    print(pid, 'ECC', round(cc, 3), 'IoU ring', round(iou, 3), 'check (m)', chk)
    # check image: plan with the model wall (blue), the 1781 works (green) and the traced works (red)
    img = cv2.imdecode(np.fromfile(os.path.join(ROOT, pl['page']), np.uint8), 1)
    ox, oy = pl['origin']
    Ai = cv2.invertAffineTransform(A)
    to_px = lambda pts: np.round((np.c_[np.asarray(pts, float), np.ones(len(pts))] @ Ai.T) * 2 + [ox, oy]).astype(np.int32)
    cv2.polylines(img, [to_px(WALL)], True, (255, 80, 0), 4)
    for grp in ('works',):
        for wk in F81[grp]: cv2.polylines(img, [to_px(wk['poly'])], True, (0, 170, 0), 5)
    for grp in ('bands', 'lines', 'water'):
        for wk in F81[grp]: cv2.polylines(img, [to_px(wk['line'])], False, (0, 170, 0), 3)
    for w in pl['works']:
        cv2.polylines(img, [np.round(np.asarray(w['poly']) * 2 + [ox, oy]).astype(np.int32)], True, (0, 0, 230), 4)
    x0, y0 = ox, oy
    crop = img[y0:y0 + 2 * 1000, x0:x0 + 2 * 1000]
    cv2.imencode('.jpg', cv2.resize(crop, None, fx=0.45, fy=0.45))[1].tofile(os.path.join(OUTD, f'_reg_{pid}.jpg'))
json.dump(out, open(os.path.join(HERE, 'fort_plans_map.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
